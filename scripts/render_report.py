#!/usr/bin/env python3
"""
Twinthos AI Security Audit — Markdown-to-HTML renderer.

Reads a security-audit.md file and produces a styled HTML report using
local assets only. No remote fetches, no analytics.
"""

import argparse
import html
import re
import sys
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
ASSETS_DIR = SCRIPT_DIR.parent / "assets"


def load_template() -> str:
    template_path = ASSETS_DIR / "report.html"
    if template_path.exists():
        return template_path.read_text(encoding="utf-8")
    return """<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="UTF-8">
<title>{{title}}</title>
<style>
{{css}}
</style>
</head>
<body>
<header>
  <h1>{{title}}</h1>
  <p class="disclaimer">Community-maintained and unofficial. Not a penetration test, certification, or monitoring service.</p>
</header>
<main>
{{content}}
</main>
<footer>
  <p>Generated by Twinthos AI Security Audit skill. Changes made: none.</p>
</footer>
</body>
</html>"""


def load_css() -> str:
    css_path = ASSETS_DIR / "report.css"
    if css_path.exists():
        return css_path.read_text(encoding="utf-8")
    return """body { font-family: system-ui, sans-serif; line-height: 1.5; max-width: 900px; margin: 0 auto; padding: 2rem; color: #1a1a1a; }
header { border-bottom: 2px solid #e5e5e5; padding-bottom: 1rem; margin-bottom: 2rem; }
h1 { font-size: 1.5rem; margin: 0; }
h2 { font-size: 1.25rem; margin-top: 2rem; border-bottom: 1px solid #e5e5e5; padding-bottom: 0.5rem; }
h3 { font-size: 1rem; margin-top: 1.5rem; }
.disclaimer { color: #666; font-size: 0.875rem; }
table { border-collapse: collapse; width: 100%; margin: 1rem 0; }
th, td { border: 1px solid #ddd; padding: 0.5rem; text-align: left; font-size: 0.875rem; }
th { background: #f5f5f5; }
pre { background: #f5f5f5; padding: 1rem; overflow-x: auto; }
code { font-family: ui-monospace, monospace; font-size: 0.875rem; }
footer { margin-top: 3rem; border-top: 1px solid #e5e5e5; padding-top: 1rem; color: #666; font-size: 0.75rem; }
.status-satisfactory { color: #1a7f37; font-weight: 600; }
.status-action_recommended { color: #b35900; font-weight: 600; }
.status-needs_confirmation { color: #0969da; font-weight: 600; }
.status-not_reviewed { color: #666; font-weight: 600; }
.status-not_applicable { color: #555; font-weight: 600; }
"""


def md_to_html(md_text: str) -> str:
    lines = md_text.splitlines()
    html = []
    in_table = False
    in_code = False
    in_list = False

    for line in lines:
        stripped = line.strip()
        safe = html.escape(stripped, quote=True)

        if stripped.startswith("```"):
            if in_code:
                html.append("</pre>")
                in_code = False
            else:
                lang = stripped[3:].strip()
                html.append(f'<pre><code class="language-{html.escape(lang, quote=True)}">')
                in_code = True
            continue
        if in_code:
            html.append(line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
            continue

        if stripped.startswith("# "):
            title = stripped[2:].strip()
            html.append(f"<h1>{html.escape(title)}</h1>")
            continue
        if stripped.startswith("## "):
            heading = stripped[3:].strip()
            html.append(f"<h2>{html.escape(heading)}</h2>")
            continue
        if stripped.startswith("### "):
            heading = stripped[4:].strip()
            html.append(f"<h3>{html.escape(heading)}</h3>")
            continue

        if stripped.startswith("| ") and "|" in stripped[1:]:
            cells = [html.escape(c.strip(), quote=True) for c in stripped.strip().strip("|").split("|")]
            if not in_table:
                html.append('<table>')
                in_table = True
                if re.match(r"^[-]+$", cells[0]):
                    continue
                html.append("<tr>" + "".join(f"<th>{c}</th>" for c in cells) + "</tr>")
            else:
                if re.match(r"^[-]+$", cells[0]):
                    continue
                row = "<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>"
                for status in ["satisfactory", "action_recommended", "needs_confirmation", "not_reviewed", "not_applicable"]:
                    if status in cells[1]:
                        row = row.replace(status, f'<span class="status-{status}">{status}</span>')
                html.append(row)
            continue
        if in_table:
            html.append("</table>")
            in_table = False

        if stripped.startswith("- "):
            if not in_list:
                html.append("<ul>")
                in_list = True
            item = html.escape(stripped[2:], quote=True)
            item = re.sub(r"\*\*(.*?)\*\*", r"<strong>\1</strong>", item)
            html.append(f"<li>{item}</li>")
            continue
        if in_list and not stripped.startswith("- "):
            html.append("</ul>")
            in_list = False
            html.append(f"<p>{safe}</p>" if stripped else "")
            continue

        if stripped == "":
            if in_list:
                html.append("</ul>")
                in_list = False
            continue

        text = re.sub(r"\*\*(.*?)\*\*", r"<strong>\1</strong>", safe)
        html.append(f"<p>{text}</p>")

    if in_table:
        html.append("</table>")
    if in_list:
        html.append("</ul>")
    if in_code:
        html.append("</pre>")

    return "\n".join(html)


def render(input_path: Path, output_path: Path) -> None:
    md_text = input_path.read_text(encoding="utf-8")
    title_match = re.search(r"^# (.+)$", md_text, re.MULTILINE)
    title = html.escape(title_match.group(1) if title_match else "AI Security Audit", quote=True)
    content = md_to_html(md_text)
    css = load_css()
    template = load_template()
    html = template.replace("{{title}}", title).replace("{{content}}", content).replace("{{css}}", css)
    output_path.write_text(html, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Render security-audit.md to HTML")
    parser.add_argument("input", type=Path, help="Path to security-audit.md")
    parser.add_argument("-o", "--output", type=Path, required=True, help="Output HTML path")
    args = parser.parse_args()
    if not args.input.exists():
        print(f"Error: {args.input} not found", file=sys.stderr)
        return 1
    render(args.input, args.output)
    print(f"Rendered {args.output}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
